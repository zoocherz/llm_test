import { test, expect } from '@playwright/test'

test('CSV reference text is mapped without requiring JSON', async ({ page }) => {
  await page.goto('/datasets')
  await page.getByText('Файл CSV / JSONL', { exact: true }).click()
  await page.locator('input[type="file"]').setInputFiles({ name: 'plain.csv', mimeType: 'text/csv', buffer: Buffer.from('id,transcript,reference_summary\n1,Input sample,Plain reference\n') })
  await page.getByRole('button', { name: 'Проверить строки', exact: true }).click()
  const panel = page.locator('.mapping-panel')
  await expect(panel.getByText('Plain reference', { exact: true })).toBeVisible()
  await panel.getByRole('button', { name: 'Применить сопоставление', exact: true }).click()
  await expect(page.getByText(/корректных строк — 1, ошибок — 0/)).toBeVisible()
  await expect(panel.locator('pre').last()).toContainText('"reference"')
  await expect(panel.locator('pre').last()).toContainText('"text": "Plain reference"')
  await panel.locator('.el-select').nth(3).click()
  await page.getByRole('option', { name: 'JSON-объект', exact: true }).click()
  await panel.getByRole('button', { name: 'Применить сопоставление', exact: true }).click()
  await expect(page.getByText(/содержит некорректный JSON/)).toBeVisible()
})

test('independent scores and selected retry stay in the original run', async ({ page, request }) => {
  test.setTimeout(90000)
  const suffix = Date.now()
  async function post(path, data) {
    const response = await request.post('/api/v1/' + path, { data })
    expect(response.ok(), await response.text()).toBeTruthy()
    return response.json()
  }
  await page.goto('/experiments?view=settings')
  const editor = page.locator('.suite-editor')
  await editor.getByRole('textbox', { name: 'Название правил', exact: true }).fill('independent-' + suffix)
  await expect(editor.getByText('Независимые оценки по своим шкалам', { exact: true })).toBeVisible()
  await editor.getByRole('button', { name: 'Добавить критерий', exact: true }).click()
  await editor.getByRole('textbox', { name: 'Код критерия 2', exact: true }).fill('style')
  await editor.getByRole('button', { name: 'Сохранить правила', exact: true }).click()
  await expect(editor.getByText(/Правила сохранены/)).toBeVisible()
  const suites = await (await request.get('/api/v1/evaluation-suites')).json()
  const suite = suites.find(row => row.name === 'independent-' + suffix)
  expect(suite.decision_rule_json.scoring_mode).toBe('independent')
  expect(suite.evaluators_json[0].criteria[1].max_score).toBe(5)
  const dataset = await post('datasets', { name: 'retry-' + suffix })
  await post('datasets/' + dataset.draft_version_id + '/items:commit', [
    { external_id: 'first', input: { text: 'first input' } }, { external_id: 'second', input: { text: 'second input' } },
  ])
  await post('datasets/' + dataset.draft_version_id + ':publish')
  const prompt = await post('prompts', { name: 'retry-prompt-' + suffix, template: '{{text}}' })
  const pipeline = await post('pipelines', { name: 'retry-pipeline-' + suffix })
  const model = await post('model-routes', { provider_name: 'offline', model_identifier: 'retry-' + suffix })
  const run = await post('runs', { dataset_version_id: dataset.draft_version_id, prompt_version_ids: [prompt.id], pipeline_version_id: pipeline.id, candidate_route_ids: [model.id] })
  await page.goto('/runs/' + run.id)
  await expect(page.locator('.el-descriptions').getByText('completed', { exact: true })).toBeVisible()
  const results = page.locator('.current-results')
  const row = results.getByRole('row').filter({ hasText: 'first input' })
  await row.locator('.el-checkbox').click()
  await expect(row.getByRole('checkbox')).toBeChecked()
  await results.getByRole('button', { name: 'Повторить выбранные', exact: true }).click()
  await expect(results.getByText(/Будет выполнено 1 вызовов/)).toBeVisible()
  await results.getByRole('button', { name: 'Подтвердить повтор', exact: true }).click()
  await expect(results.getByRole('button', { name: 'Попытки: 2', exact: true })).toBeVisible()
  await expect(page).toHaveURL(new RegExp(run.id + '$'))
  const details = await (await request.get('/api/v1/runs/' + run.id + '/details')).json()
  expect(details.find(row => row.dataset_item.external_id === 'second').attempts).toHaveLength(1)
  const judge = await post('prompts', { name: 'judge-' + suffix, template: '{{output}}' })
  const evaluation = await post('runs/' + run.id + '/evaluations', { judge_route_id: model.id, judge_prompt_id: judge.id, suite_version_id: suite.id })
  await page.goto('/runs/' + evaluation.id)
  await expect(page.locator('.el-descriptions').getByText('completed', { exact: true })).toBeVisible()
  await expect(page.locator('.el-descriptions').getByText('Оценка судьёй', { exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'quality (0–5)', exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'style (0–5)', exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Средняя оценка', exact: true })).toHaveCount(0)
  expect(await page.locator('.runs-view').evaluate(el => el.firstElementChild.classList.contains('current-results'))).toBe(true)
})
